"""AsmLine -> .s text (Spec 6.5, 6.6): column layout, string interning, ASCII-only, E040."""

from __future__ import annotations

from c2mips import RUNTIME_S, __version__
from c2mips.codegen import AsmLine, Blank, Comment, Directive, Insn, Label, StrRef
from c2mips.diagnostics import error
from c2mips.fpga import emit_fpga
from c2mips.tokens import Pos

MAX_INSNS = 32000  # Q22: keeps every `beq ... __rt_div0` within the 16-bit branch range
COMMENT_COL = 36
_ASCIIZ_ESC = {"\n": "\\n", "\t": "\\t", '"': '\\"'}


def emit(lines: list[AsmLine], source_name: str, *, where: Pos, runtime: bool = True,
         opt: str = "-O0", target: str = "spim") -> str:
    n_insns = sum(isinstance(ln, Insn) for ln in lines)
    if n_insns > MAX_INSNS:
        raise error("E040", f"program too large: {n_insns} instructions (limit {MAX_INSNS})",
                    where)
    if target == "fpga":
        return emit_fpga(lines, runtime=runtime)  # ADR-009: no header, data or comments
    labels: dict[str, str] = {}
    for ln in lines:
        if isinstance(ln, Insn):
            for a in ln.args:
                if isinstance(a, StrRef) and a.text not in labels:
                    labels[a.text] = f"__str{len(labels)}"

    out = [f"# generated by c2mips {__version__.rsplit('.', 1)[0]} ({opt}) from {source_name}",
           "        .data"]
    out += [f"{label}: {_string_directive(text)}" for text, label in labels.items()]
    out.append("")
    out += [_format(ln, labels) for ln in lines]
    text = "\n".join(out) + "\n"
    if runtime:
        text += "\n" + RUNTIME_S.read_text(encoding="ascii")
    assert text.isascii(), "emitter must only produce ASCII (SPIM hangs otherwise, S8)"
    return text


def _with_comment(code: str, comment: str) -> str:
    return f"{code:<{COMMENT_COL - 1}} # {comment}" if comment else code


def _format(ln: AsmLine, labels: dict[str, str]) -> str:
    match ln:
        case Insn(op=op, args=args, comment=comment):
            ops = ", ".join(labels[a.text] if isinstance(a, StrRef) else a for a in args)
            code = f"        {op:<6}{ops}" if ops else f"        {op}"
            return _with_comment(code, _ascii(comment))
        case Label(name=name, comment=comment):
            return _with_comment(f"{name}:", _ascii(comment))
        case Directive(text=text):
            return f"        {text}"
        case Comment(text=text):
            return f"# {_ascii(text)}"
        case Blank():
            return ""
    raise TypeError(ln)


def _ascii(text: str) -> str:
    """Escape anything SPIM cannot take, even inside a comment (S8)."""
    out = []
    for c in text:
        if c == "\t":
            out.append(" ")
        elif " " <= c <= "~":
            out.append(c)
        else:
            out.append(f"\\u{ord(c):04x}")
    return "".join(out)


def _string_directive(s: str) -> str:
    """.asciiz only for printable ASCII without backslash (plus \\n \\t); else .byte (6.6).

    .byte values >= 0x80 are written negative: same bytes, but MARS warns on stdout for
    values above 127 (S17, ADR-007).
    """
    if all((" " <= c <= "~" and c != "\\") or c in "\n\t" for c in s):
        return '.asciiz "' + "".join(_ASCIIZ_ESC.get(c, c) for c in s) + '"'
    data = [b - 256 if b > 127 else b for b in s.encode("utf-8")] + [0]
    return ".byte " + ", ".join(map(str, data))
