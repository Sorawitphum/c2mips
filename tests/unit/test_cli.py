"""CLI (Spec 2): -o, --emit, --no-runtime, --run, exit codes 0/1/2."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest
from conftest import REPO, sim_cli

from c2mips import RUNTIME_S
from c2mips.__main__ import main

SRC = 'int main(void) {\n    printf("hi %d\\n", 6 * 7);\n    return 3;\n}\n'


@pytest.fixture
def cfile(tmp_path: Path) -> Path:
    p = tmp_path / "prog.c"
    p.write_text(SRC, encoding="utf-8")
    return p


def test_default_output_name(cfile: Path) -> None:
    assert main([str(cfile)]) == 0
    out = cfile.with_suffix(".s").read_text(encoding="ascii")
    assert out.startswith("# generated by c2mips 0.1 (-O0) from prog.c\n")
    assert out.endswith(RUNTIME_S.read_text(encoding="ascii"))


def test_dash_o_and_no_runtime(cfile: Path, tmp_path: Path) -> None:
    out = tmp_path / "x.s"
    assert main([str(cfile), "-o", str(out), "--no-runtime"]) == 0
    assert "__rt_nCk:" not in out.read_text(encoding="ascii")


def test_emit_tokens(cfile: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert main([str(cfile), "--emit=tokens"]) == 0
    lines = capsys.readouterr().out.splitlines()
    assert lines[0] == "1:1\tINT\tint"
    assert lines[-1] == "5:1\tEOF\t"
    assert not cfile.with_suffix(".s").exists()


def test_emit_ast(cfile: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert main([str(cfile), "--emit=ast"]) == 0
    assert capsys.readouterr().out == (
        '(program (function main () (block (printf ("hi " %d "\\n") (* 6 7)) (return 3))))\n')


def test_emit_asm(cfile: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert main([str(cfile), "--emit=asm", "--no-runtime"]) == 0
    assert capsys.readouterr().out.splitlines()[0].startswith("# generated by c2mips")


def test_missing_file_is_exit_2(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert main([str(tmp_path / "nope.c")]) == 2
    assert "nope.c" in capsys.readouterr().err


def test_invalid_utf8_is_exit_2(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    p = tmp_path / "bad.c"
    p.write_bytes(b"int main(void) { return 0; } /* \xff */\n")
    assert main([str(p)]) == 2
    assert "UTF-8" in capsys.readouterr().err


def test_bad_usage_is_exit_2(capsys: pytest.CaptureFixture[str]) -> None:
    with pytest.raises(SystemExit) as e:
        main(["--emit=bogus", "x.c"])
    assert e.value.code == 2


def test_o1(cfile: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert main([str(cfile), "-O1", "--emit=asm", "--no-runtime"]) == 0
    out = capsys.readouterr().out
    assert out.startswith("# generated by c2mips 0.1 (-O1) from prog.c\n")
    assert "        li    $a0, 42" in out  # 6 * 7 folded, then printed straight from $a0


def test_compile_error_is_exit_1(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    p = tmp_path / "e.c"
    p.write_text("int main(void) { return 1 }\n", encoding="utf-8")
    assert main([str(p)]) == 1
    assert "error[E010]" in capsys.readouterr().err


def test_python_dash_m(cfile: Path) -> None:
    p = subprocess.run([sys.executable, "-m", "c2mips", str(cfile), "--emit=ast"],
                       capture_output=True, text=True)
    assert p.returncode == 0
    assert p.stdout.startswith("(program")


@pytest.mark.sim
def test_run_forwards_stdout_and_exit_code(cfile: Path, monkeypatch: pytest.MonkeyPatch,
                                           capfd: pytest.CaptureFixture[str]) -> None:
    sim = sim_cli(monkeypatch)
    assert main([str(cfile), "--run", *sim]) == 3
    assert capfd.readouterr().out == "hi 42\n"


@pytest.mark.sim
def test_run_forwards_stdin_for_scanf(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    src = REPO / "tests" / "programs" / "scanf_basic.c"
    sim = sim_cli(monkeypatch)  # sets SPIM / MARS_JAR for the child process too
    p = subprocess.run([sys.executable, "-m", "c2mips", str(src), "-o", str(tmp_path / "s.s"),
                        "--run", *sim], input=(src.with_suffix(".stdin")).read_text(),
                       capture_output=True, text=True, timeout=120)
    assert (p.stdout.replace("\r\n", "\n"), p.returncode) == ("12 -85 -3\nsum 60\n", 22)


@pytest.mark.parametrize(("sim", "message"), [
    ("auto", "no simulator found"), ("spim", "spim not found"), ("mars", "MARS needs java"),
])
def test_run_without_a_simulator_is_exit_2(cfile: Path, monkeypatch: pytest.MonkeyPatch,
                                           capsys: pytest.CaptureFixture[str], sim: str,
                                           message: str) -> None:
    monkeypatch.delenv("SPIM", raising=False)
    monkeypatch.delenv("MARS_JAR", raising=False)
    monkeypatch.setattr("shutil.which", lambda name: None)
    assert main([str(cfile), "--run", "--sim", sim]) == 2
    assert message in capsys.readouterr().err


def test_warning_still_compiles(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    p = tmp_path / "w.c"
    p.write_text("int f(int x) { if (x) return 1; }\nint main(void) { return f(0); }\n",
                 encoding="utf-8")
    assert main([str(p)]) == 0
    err = capsys.readouterr().err
    assert ": warning[W001]: control may reach the end of 'f'" in err
    assert p.with_suffix(".s").exists()


@pytest.mark.sim
def test_run_exit_code_is_8_bits(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                                 capfd: pytest.CaptureFixture[str]) -> None:
    # `return -1;` exits 255 on every OS and simulator (java on Windows would say 4294967295)
    p = tmp_path / "neg.c"
    p.write_text("int main(void) { return -1; }\n", encoding="utf-8")
    assert main([str(p), "--run", *sim_cli(monkeypatch)]) == 255
